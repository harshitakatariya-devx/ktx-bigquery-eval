"""Step 4: build SQL that checks description claims against data: 'unique' ID columns, and 'e.g.' example values
for categorical columns. Run: uv run --with pyyaml python eval/audit/d2_description_claims.py > eval/audit/d2_description_claims.sql"""
import re
from pathlib import Path

import yaml

schema = yaml.safe_load(Path("semantic-layer/warehouse/_schema/dev_dna_silver.yaml").read_text())["tables"]
T = lambda t: f"`sahil-devx.dev_dna_silver.{t}`"
UNIQUE = [("customers_master", "customer_master_id"), ("dim_customer", "customer_master_id"), ("dim_d2c_order", "order_name"),
          ("employees", "employee_id"), ("international_orders", "order_ref"), ("marketing_spend", "spend_id"),
          ("shipments", "shipment_id"), ("suppliers", "supplier_id"), ("product_bundle", "bundle_id"),
          ("promotions", "promo_id"), ("purchase_orders", "po_id"), ("returns", "return_id"), ("item_master", "product_id")]
has_deleted = lambda t: any(c["name"] == "is_deleted" for c in schema[t]["columns"])
parts = [f"select 'unique' chk, '{t}.{c}' col, cast(count(*) as string) a, cast(count(distinct {c}) as string) b from {T(t)}"
         + (" where not coalesce(is_deleted, false)" if has_deleted(t) else "")
         for t, c in UNIQUE]
for t, entry in schema.items():
    for c in entry["columns"]:
        db = (c.get("descriptions") or {}).get("db", "")
        if c.get("type") == "string" and re.search(r"\(e\.g\.", db) and not c["name"].endswith(("_id", "_ref", "_name", "_code", "_no", "email", "phone", "city")):
            examples = re.search(r"\(e\.g\.([^)]*)\)", db).group(1).strip().replace("'", "")
            parts.append(f"select 'examples', '{t}.{c['name']}', '{examples}', "
                         f"(select string_agg(v, ', ' order by v) from (select distinct {c['name']} v from {T(t)} where {c['name']} is not null limit 25)) from (select 1)")
print("-- Step 4: description claims vs data (generated by d2_description_claims.py)\n" + "\nunion all\n".join(parts) + "\norder by 1, 2")
